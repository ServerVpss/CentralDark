import crypto from 'node:crypto';

export const PDF_CORE_VERSION = 'centraldark.pdf-harness-core.v1';

const TASK_RULES = [
  {
    id: 'REDACT',
    match: /redact|reda[cç][aã]o|remove underlying|sigilo|ocultar/i,
    pipeline: ['preflight', 'render_input', 'true_redaction', 'render_output', 'visual_diff', 'receipt'],
    ownerHint: 'pdfs/tasks/redact.md',
  },
  {
    id: 'OCR',
    match: /ocr|scan|scanned|digitalizar|pesquis[aá]vel|imagem para texto/i,
    pipeline: ['preflight', 'render_input', 'ocr', 'render_output', 'text_extract_verify', 'receipt'],
    ownerHint: 'pdfs/tasks/ocr.md',
  },
  {
    id: 'FORMS',
    match: /form|campo|acroform|preencher|flatten|checkbox|assinatura/i,
    pipeline: ['preflight', 'inspect_forms', 'fill_or_stamp', 'render_output', 'field_value_verify', 'receipt'],
    ownerHint: 'pdfs/tasks/forms_annotations.md',
  },
  {
    id: 'EXTRACT',
    match: /extract|extrair|tabela|imagem|anexo|texto|coordenada|layout/i,
    pipeline: ['preflight', 'render_input', 'extract', 'layout_verify', 'receipt'],
    ownerHint: 'pdfs/tasks/extract.md',
  },
  {
    id: 'EDIT',
    match: /merge|split|rotate|crop|watermark|paginate|encrypt|repair|juntar|dividir|girar|cortar/i,
    pipeline: ['preflight', 'render_input', 'edit', 'render_output', 'visual_diff', 'receipt'],
    ownerHint: 'pdfs/tasks/edit.md',
  },
  {
    id: 'CONVERT',
    match: /convert|converter|docx|pptx|html|markdown|latex/i,
    pipeline: ['choose_authoring_format', 'convert_to_pdf', 'render_output', 'glyph_layout_verify', 'receipt'],
    ownerHint: 'pdfs/tasks/convert.md',
  },
  {
    id: 'CREATE',
    match: /create|criar|gerar|author|relat[oó]rio|documento/i,
    pipeline: ['choose_authoring_format', 'create_source', 'convert_or_render_pdf', 'render_output', 'glyph_layout_verify', 'receipt'],
    ownerHint: 'pdfs/tasks/create.md',
  },
];

export function sha256Hex(value) {
  return crypto.createHash('sha256').update(String(value), 'utf8').digest('hex');
}

export function chooseAuthoringFormat(text) {
  const value = String(text ?? '');
  if (/slide|deck|pptx|apresenta[cç][aã]o|callout|fixed positioning|chart|figura/i.test(value)) return 'PPTX_THEN_PDF';
  if (/business|toc|heading|long table|texto longo|sum[aá]rio|tabela longa|rich list/i.test(value)) return 'DOCX_THEN_PDF';
  if (/programmatic|reportlab|generated by code|gerar por c[oó]digo/i.test(value)) return 'REPORTLAB_DIRECT';
  return 'PDF_SKILL_DEFAULT';
}

export function classifyPdfTask(input) {
  const text = [input?.intent, input?.operation, input?.notes, input?.filename].filter(Boolean).join('\n');
  const rule = TASK_RULES.find((candidate) => candidate.match.test(text)) ?? {
    id: 'READ_REVIEW',
    pipeline: ['preflight', 'render_input', 'inspect_pngs', 'read_review', 'receipt'],
    ownerHint: 'pdfs/tasks/read_review.md',
  };

  return {
    task: rule.id,
    ownerHint: rule.ownerHint,
    pipeline: rule.pipeline,
    authoringFormat: chooseAuthoringFormat(text),
  };
}

export function buildPdfPlan(input = {}) {
  const observedAt = input.observed_at ?? new Date(0).toISOString();
  const classification = classifyPdfTask(input);
  const materialId = sha256Hex(JSON.stringify({
    intent: input.intent ?? '',
    operation: input.operation ?? '',
    filename: input.filename ?? '',
    notes: input.notes ?? '',
  })).slice(0, 16);

  return {
    schema: PDF_CORE_VERSION,
    status: 'PLAN',
    material_id: materialId,
    observed_at: observedAt,
    authority: 'SEGREDO/CHEFE',
    owner: 'docs/ARQUITETURA/CENTRALDARK-TRIGGER-FABRIC/PDF-HARNESS-BRIDGE.md',
    connector_role: 'MCP_OR_HARNESS_BRIDGE',
    mutation_policy: 'DETERMINISTIC_POINT_OF_FAILURE_ONLY',
    unknown_is_not_pass: true,
    render_loop_required: classification.pipeline.some((step) => step.includes('render')),
    task: classification.task,
    authoring_format: classification.authoringFormat,
    owner_hint: classification.ownerHint,
    pipeline: classification.pipeline,
    gates: [
      'RENDER_BEFORE_OPERATE_WHEN_INPUT_PDF',
      'VERIFY_RENDER_AFTER_OUTPUT',
      'TRUE_REDACTION_FOR_REDACTION',
      'NO_CLIPPED_TEXT_OR_BROKEN_GLYPHS',
      'RECEIPT_WITH_NEXT_CURSOR',
    ],
    next_cursor: 'EXECUTE_SMALLEST_PDF_TASK_THROUGH_RENDER_VERIFY_LOOP',
  };
}

export function validatePdfPlan(plan) {
  const errors = [];
  if (!plan || plan.schema !== PDF_CORE_VERSION) errors.push('PDF_PLAN_SCHEMA_INVALID');
  if (plan?.unknown_is_not_pass !== true) errors.push('UNKNOWN_IS_NOT_PASS_MISSING');
  if (!Array.isArray(plan?.pipeline) || plan.pipeline.length === 0) errors.push('PIPELINE_EMPTY');
  if (plan?.task === 'REDACT' && !plan.pipeline.includes('true_redaction')) errors.push('REDACTION_WITHOUT_TRUE_REDACTION');
  if (plan?.render_loop_required && !plan.pipeline.some((s) => s.includes('render'))) errors.push('RENDER_LOOP_MISSING');
  if (!plan?.next_cursor) errors.push('NEXT_CURSOR_MISSING');
  return { ok: errors.length === 0, errors };
}
